import 'dart:convert';
import 'dart:math' as math;

import 'package:shared_preferences/shared_preferences.dart';

/// Hands out questions from a shuffled deck that is remembered on the phone: every question in the bank is used
/// once before any comes back, and each new round of the deck starts in a different order.
class NgmyQuestionDeck {
  NgmyQuestionDeck._();

  static SharedPreferences? _prefs;
  static final Map<String, ({List<int> order, int pos})> _decks = {};

  static Future<void> warmUp() async {
    try {
      _prefs ??= await SharedPreferences.getInstance();
    } catch (_) {}
  }

  static int next(String key, int count, math.Random rng) {
    if (count <= 0) return 0;
    var deck = _decks[key] ?? _load(key, count);
    if (deck == null || deck.order.length != count || deck.pos >= count) {
      final last = deck != null && deck.order.isNotEmpty ? deck.order.last : -1;
      final order = List<int>.generate(count, (i) => i)..shuffle(rng);
      // The first question of a new round is never the last one of the old round.
      if (count > 1 && order.first == last) {
        final j = 1 + rng.nextInt(count - 1);
        final t = order[0];
        order[0] = order[j];
        order[j] = t;
      }
      deck = (order: order, pos: 0);
    }
    final pick = deck.order[deck.pos];
    _decks[key] = (order: deck.order, pos: deck.pos + 1);
    _save(key);
    return pick;
  }

  static ({List<int> order, int pos})? _load(String key, int count) {
    final raw = _prefs?.getString('ngmy_deck_$key');
    if (raw == null) return null;
    try {
      final j = jsonDecode(raw) as Map<String, dynamic>;
      final order = [for (final e in (j['o'] as List)) (e as num).toInt()];
      if (order.length != count) return null;
      return (order: order, pos: (j['p'] as num).toInt());
    } catch (_) {
      return null;
    }
  }

  static void _save(String key) {
    final d = _decks[key];
    final p = _prefs;
    if (d == null || p == null) return;
    p.setString('ngmy_deck_$key', jsonEncode({'o': d.order, 'p': d.pos}));
  }
}

