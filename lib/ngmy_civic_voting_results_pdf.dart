import 'dart:typed_data';

import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import 'ngmy_civic_voting.dart';

Future<Uint8List> ngmyBuildCivicVotingResultsPdfBytes({
  required NgmyCivicVotingState voting,
}) async {
  final sorted = [...voting.candidates]
    ..sort((a, b) => voting.votesFor(b.id).compareTo(voting.votesFor(a.id)));
  final total = sorted.fold<int>(0, (n, c) => n + voting.votesFor(c.id));
  final title = voting.title.trim().isEmpty ? 'CIVIC VOTING' : voting.title.trim().toUpperCase();
  final year = voting.yearLabel.trim();
  final dateLine = voting.dateLabel.trim().isEmpty
      ? (voting.scheduleOpenDate.trim().isEmpty ? '—' : voting.scheduleOpenDate.trim())
      : voting.dateLabel.trim();
  final now = DateTime.now().toLocal();
  final stamp =
      '${now.year.toString().padLeft(4, '0')}-${now.month.toString().padLeft(2, '0')}-${now.day.toString().padLeft(2, '0')}';

  final doc = pw.Document(title: '$title Results', creator: 'NGMY');

  doc.addPage(
    pw.MultiPage(
      pageFormat: PdfPageFormat.letter,
      margin: const pw.EdgeInsets.fromLTRB(40, 40, 40, 44),
      footer: (ctx) => pw.Align(
        alignment: pw.Alignment.centerRight,
        child: pw.Text(
          'NGMY.ORG · Page ${ctx.pageNumber} of ${ctx.pagesCount}',
          style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey600),
        ),
      ),
      build: (ctx) => [
        pw.Row(
          mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
          children: [
            pw.Text(stamp, style: pw.TextStyle(fontSize: 10, fontWeight: pw.FontWeight.bold, color: PdfColors.grey700)),
            pw.Text(
              year.isEmpty ? 'CIVIC REGISTRY' : year,
              style: pw.TextStyle(fontSize: 10, fontWeight: pw.FontWeight.bold, color: PdfColors.green800),
            ),
          ],
        ),
        pw.SizedBox(height: 10),
        pw.Text(
          title,
          style: pw.TextStyle(fontSize: 20, fontWeight: pw.FontWeight.bold, color: PdfColors.black),
        ),
        pw.SizedBox(height: 4),
        pw.Text(
          'Official voting results · $dateLine',
          style: const pw.TextStyle(fontSize: 11, color: PdfColors.grey700),
        ),
        pw.SizedBox(height: 6),
        pw.Container(
          height: 1.2,
          color: PdfColors.green700,
        ),
        pw.SizedBox(height: 14),
        pw.Table(
          border: pw.TableBorder.all(color: PdfColors.grey400, width: 0.7),
          columnWidths: {
            0: const pw.FlexColumnWidth(0.7),
            1: const pw.FlexColumnWidth(3.2),
            2: const pw.FlexColumnWidth(1.1),
          },
          children: [
            pw.TableRow(
              decoration: const pw.BoxDecoration(color: PdfColors.grey200),
              children: [
                _cell('RANK', bold: true, center: true),
                _cell('CANDIDATE', bold: true),
                _cell('VOTES', bold: true, center: true),
              ],
            ),
            ...sorted.asMap().entries.map((e) {
              final rank = e.key + 1;
              final c = e.value;
              final votes = voting.votesFor(c.id);
              return pw.TableRow(
                children: [
                  _cell('$rank', center: true, bold: rank == 1),
                  _cell(c.name.trim().isEmpty ? '—' : c.name.trim(), bold: rank == 1),
                  _cell('$votes', center: true, bold: rank == 1),
                ],
              );
            }),
            pw.TableRow(
              decoration: const pw.BoxDecoration(color: PdfColors.grey100),
              children: [
                _cell('', bold: true),
                _cell('TOTAL', bold: true),
                _cell('$total', bold: true, center: true),
              ],
            ),
          ],
        ),
        pw.SizedBox(height: 18),
        pw.Text(
          'One vote per linked Civic Registry member. Generated by NGMY Civic Voting.',
          style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey600),
        ),
      ],
    ),
  );

  return doc.save();
}

pw.Widget _cell(String text, {bool bold = false, bool center = false}) {
  return pw.Padding(
    padding: const pw.EdgeInsets.symmetric(horizontal: 8, vertical: 7),
    child: pw.Text(
      text,
      textAlign: center ? pw.TextAlign.center : pw.TextAlign.left,
      style: pw.TextStyle(
        fontSize: 11,
        fontWeight: bold ? pw.FontWeight.bold : pw.FontWeight.normal,
      ),
    ),
  );
}

String ngmyCivicVotingResultsPaperHtml({
  required NgmyCivicVotingState voting,
}) {
  String esc(String s) => s
      .replaceAll('&', '&amp;')
      .replaceAll('<', '&lt;')
      .replaceAll('>', '&gt;')
      .replaceAll('"', '&quot;');

  final sorted = [...voting.candidates]
    ..sort((a, b) => voting.votesFor(b.id).compareTo(voting.votesFor(a.id)));
  final total = sorted.fold<int>(0, (n, c) => n + voting.votesFor(c.id));
  final title = voting.title.trim().isEmpty ? 'CIVIC VOTING' : voting.title.trim().toUpperCase();
  final year = voting.yearLabel.trim();
  final dateLine = voting.dateLabel.trim().isEmpty ? '—' : voting.dateLabel.trim();
  final now = DateTime.now().toLocal();
  final stamp =
      '${now.year.toString().padLeft(4, '0')}-${now.month.toString().padLeft(2, '0')}-${now.day.toString().padLeft(2, '0')}';

  final rows = StringBuffer();
  for (var i = 0; i < sorted.length; i++) {
    final c = sorted[i];
    final votes = voting.votesFor(c.id);
    rows.writeln('''
      <tr>
        <td class="rank">${i + 1}</td>
        <td>${esc(c.name.trim().isEmpty ? '—' : c.name.trim())}</td>
        <td class="num">$votes</td>
      </tr>''');
  }

  return '''
<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8"/>
<title>NGMY.ORG · Voting Results</title>
<style>
  @page { size: letter; margin: 12mm; }
  html, body { margin: 0; padding: 0; background: #fff; color: #111;
    font-family: Georgia, "Times New Roman", serif; }
  .sheet { padding: 8px; }
  .meta { display: flex; justify-content: space-between; font-size: 11px;
    font-family: system-ui, sans-serif; margin-bottom: 8px; font-weight: 700; color: #166534; }
  h1 { margin: 0 0 4px; font-size: 22px; font-weight: 800; letter-spacing: 0.3px; }
  .sub { margin: 0 0 12px; font-size: 12px; color: #444; font-family: system-ui, sans-serif; }
  .rule { height: 2px; background: #166534; margin-bottom: 14px; }
  table { width: 100%; border-collapse: collapse; font-family: system-ui, sans-serif; }
  th, td { border: 1px solid #ccc; padding: 8px 10px; font-size: 13px; }
  th { background: #f3f4f6; text-align: left; font-weight: 800; font-size: 11px; }
  td.rank, th.rank, td.num, th.num { text-align: center; }
  tfoot td { font-weight: 800; background: #f9fafb; }
  .note { margin-top: 16px; font-size: 10px; color: #666; font-family: system-ui, sans-serif; }
</style>
</head>
<body>
  <div class="sheet">
    <div class="meta"><span>$stamp</span><span>${esc(year.isEmpty ? 'CIVIC REGISTRY' : year)}</span></div>
    <h1>${esc(title)}</h1>
    <p class="sub">Official voting results · ${esc(dateLine)}</p>
    <div class="rule"></div>
    <table>
      <thead>
        <tr>
          <th class="rank">RANK</th>
          <th>CANDIDATE</th>
          <th class="num">VOTES</th>
        </tr>
      </thead>
      <tbody>
        $rows
      </tbody>
      <tfoot>
        <tr>
          <td></td>
          <td>TOTAL</td>
          <td class="num">$total</td>
        </tr>
      </tfoot>
    </table>
    <p class="note">One vote per linked Civic Registry member. Generated by NGMY Civic Voting.</p>
  </div>
  <script>
    window.addEventListener('load', function () {
      setTimeout(function () { try { window.print(); } catch (e) {} }, 180);
    });
  </script>
</body>
</html>''';
}
