RepairGuide _carSeed({
  required String id,
  required String make,
  required String model,
  required int year,
  String variant = '',
  required String repairTitle,
  required String summary,
  required String coverUrl,
  required List<RepairGuideStep> steps,
  required DateTime now,
}) {
  return RepairGuide(
    id: id,
    categoryId: 'car',
    make: make,
    model: model,
    year: year,
    variant: variant,
    repairTitle: repairTitle,
    summary: summary,
    coverImageUrl: coverUrl,
    steps: steps,
    authorEmail: 'ngmy@seed',
    createdAt: now,
    updatedAt: now,
    isSeed: true,
  );
}

RepairGuideStep _step(
  int order,
  String title,
  String body,
  String imageUrl, {
  List<String> tools = const [],
  String? warning,
}) {
  return RepairGuideStep(
    order: order,
    title: title,
    body: body,
    imageUrl: imageUrl,
    tools: tools,
    warning: warning,
  );
}

