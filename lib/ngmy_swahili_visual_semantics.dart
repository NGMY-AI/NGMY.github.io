/// True when [token] appears as a whole word/phrase in [hay] — avoids "mrefu" inside "maarufu".
bool ngmySwahiliTokenMatch(String hay, String token) {
  if (token.contains(' ')) return hay.contains(token);
  if (hay == token) return true;
  return RegExp('(?:^|\\s)${RegExp.escape(token)}(?:\\s|\$|[.,!?])').hasMatch(hay);
}

SwahiliWordVisual matchSemanticSwahiliVisual(SwahiliWord word) {
  final sw = _normSwKey(word.swahili);
  final en = word.english.toLowerCase();
  for (final rule in _kSemanticRules) {
    if (rule.test(sw, en)) return rule.visual;
  }
  return const SwahiliWordVisual(
    imageUrl: 'https://images.unsplash.com/photo-1456513080510-7bf3a84b82f8?w=960&h=720&fit=crop&q=92&auto=format&dpr=2',
    caption: 'Learn',
  );
}

final Map<String, SwahiliWordVisual> _curriculumVisualCache = {};
var _curriculumVisualsReady = false;

void _ensureCurriculumVisuals() {
  if (_curriculumVisualsReady) return;
  for (final level in kSwahiliLevels) {
    for (final day in level.days) {
      for (final word in day.words) {
        final key = _normSwKey(word.swahili);
        _curriculumVisualCache[key] = matchSemanticSwahiliVisual(word);
      }
    }
  }
  _curriculumVisualsReady = true;
}

/// Pre-mapped visual for a curriculum word (exact Swahili phrase).
SwahiliWordVisual? curriculumSwahiliVisual(String swahili) {
  _ensureCurriculumVisuals();
  return _curriculumVisualCache[_normSwKey(swahili)];
}
